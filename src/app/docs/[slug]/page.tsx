import { notFound } from 'next/navigation'
import Link from 'next/link'
import { createClient } from '@/lib/supabase/server'
import { MarkdownRenderer } from '@/components/ui/markdown-renderer'
import { getCompanyTemplate } from '@/lib/company/templates'
import type { CompanyDocType } from '@/lib/company/templates'

// HOSTING_ACTIVE: This page is built and ready.
// To activate hosted docs:
// 1. Set project.hosting_active = true in the database
// 2. Remove the HOSTING_DISABLED check below
// 3. For custom domains: configure wildcard DNS + Vercel custom domains API
// 4. For free tier subdomain: portforge.io/docs/[slug] works immediately

const HOSTING_DISABLED = true // ← flip to false when ready to activate

interface DocSection {
  id: string
  title: string
  content: string
  order: number
}

interface Props { params: Promise<{ slug: string }> }

export default async function HostedDocsPage({ params }: Props) {
  if (HOSTING_DISABLED) notFound()

  const { slug } = await params
  const supabase = await createClient()

  const { data: project } = await supabase
    .from('company_projects')
    .select('*')
    .eq('slug', slug)
    .eq('hosting_active', true)
    .single()

  if (!project) notFound()

  const sections = (project.sections || []) as DocSection[]
  const template = getCompanyTemplate(project.doc_type as CompanyDocType)

  return (
    <div className="min-h-screen bg-forge-black">
      {/* Docs nav */}
      <nav className="flex items-center justify-between px-8 py-4 border-b border-white/5 sticky top-0 bg-forge-black/90 backdrop-blur z-10">
        <div className="flex items-center gap-3">
          <Link href="/" className="flex items-center gap-1.5 text-white/30 hover:text-white transition-colors">
            <div className="w-5 h-5 bg-forge-purple rounded flex items-center justify-center">
              <svg width="10" height="10" viewBox="0 0 14 14" fill="none">
                <rect x="1" y="1" width="5" height="7" rx="1" fill="#EEEDFE"/>
                <rect x="8" y="1" width="5" height="4" rx="1" fill="#AFA9EC"/>
                <rect x="1" y="10" width="5" height="3" rx="1" fill="#AFA9EC"/>
                <rect x="8" y="7" width="5" height="6" rx="1" fill="#EEEDFE"/>
              </svg>
            </div>
          </Link>
          <span className="text-white/20">/</span>
          <span className="text-sm font-medium">{project.name}</span>
          {template && <span className="text-xs text-white/30">— {template.name}</span>}
        </div>
        <Link href="/signup" className="text-xs text-forge-lilac hover:text-white transition-colors">
          Create docs with Portforge →
        </Link>
      </nav>

      <div className="flex max-w-6xl mx-auto">
        {/* Section sidebar */}
        <aside className="w-56 shrink-0 sticky top-[57px] h-[calc(100vh-57px)] overflow-y-auto border-r border-white/5 p-4">
          <p className="forge-label mb-3">Contents</p>
          <nav className="flex flex-col gap-1">
            {sections.sort((a, b) => a.order - b.order).map(section => (
              <a key={section.id} href={`#${section.id}`}
                className="text-xs text-white/50 hover:text-white py-1.5 px-2 rounded hover:bg-white/5 transition-all">
                {section.title}
              </a>
            ))}
          </nav>
        </aside>

        {/* Docs content */}
        <main className="flex-1 px-12 py-10 max-w-3xl">
          {sections.sort((a, b) => a.order - b.order).map(section => (
            <section key={section.id} id={section.id} className="mb-16 scroll-mt-20">
              <MarkdownRenderer content={section.content}/>
            </section>
          ))}

          <div className="border-t border-white/5 pt-8 mt-8">
            <p className="text-xs text-white/20">
              Documentation generated by{' '}
              <Link href="/" className="text-forge-lilac hover:underline">Portforge</Link>
            </p>
          </div>
        </main>
      </div>
    </div>
  )
}
